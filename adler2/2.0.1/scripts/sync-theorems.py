#!/usr/bin/env python3
"""Generate or check Lean theorem audits from the canonical inventory."""
import argparse
import json
import re
import sys
import tomllib
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
inventory = json.loads((ROOT / "verification/theorems.json").read_text())
checked = inventory["checked"]
names = [item["name"] for item in checked]
if len(set(names)) != len(names) or not names:
    raise SystemExit("duplicate or empty checked theorem inventory")
if any(not re.fullmatch(r"[A-Za-z_][A-Za-z_0-9.]*", name) for name in names):
    raise SystemExit("invalid Lean theorem name")
mapping = inventory["recorder_mappings"]
if any(item["theorem"] not in names for item in mapping):
    raise SystemExit("recorder mapping has unaudited theorem")
checked_by_name = {item["name"]: item for item in checked}
toml = tomllib.loads((ROOT / "proofs.toml").read_text())
actual_mapping = [{"api": p["api"], "theorem": p["theorem"]} for p in toml["tool"]["proofs"]]
if actual_mapping != mapping:
    raise SystemExit("proofs.toml mapping differs from theorem inventory")
for proof in toml["tool"]["proofs"]:
    theorem = checked_by_name[proof["theorem"]]
    if proof["module"] != theorem["module"] or proof["precondition"] != "true":
        raise SystemExit(f"module/precondition mismatch for {proof['api']}")

audit = """-- Generated by scripts/sync-theorems.py from verification/theorems.json.
import Lean
import Proofs
open Lean Elab Command

run_cmd do
  let names : List Name := [
"""
audit += ",\n".join(f"    `{name}" for name in names) + "\n  ]\n"
audit += """  for theoremName in names do
    match (← getEnv).find? theoremName with
    | some (.thmInfo _) => pure ()
    | _ => throwError "Expected a theorem: {theoremName}"
    let axioms ← Lean.collectAxioms theoremName
    for ax in axioms do
      unless [``propext, ``Classical.choice, ``Quot.sound].contains ax do
        throwError "Disallowed axiom in {theoremName}: {ax}"
    logInfo m!"AUDIT OK: {theoremName}; axioms: {axioms}"
"""
recorder = """-- Generated by scripts/sync-theorems.py from verification/theorems.json.
import Lean
"""
recorder += "".join(f"import {module}\n" for module in dict.fromkeys(checked_by_name[item["theorem"]]["module"] for item in mapping))
recorder += """open Lean Elab Command

run_cmd do
  let names : List Name := [
"""
recorder += ",\n".join(f"    `{item['theorem']}" for item in mapping) + "\n  ]\n"
recorder += """  for theorem_name in names do
    match (← getEnv).find? theorem_name with
    | some (.thmInfo _) => pure ()
    | _ => throwError "Expected a theorem: {theorem_name}"
    let axioms ← Lean.collectAxioms theorem_name
    for ax in axioms do
      unless [``propext, ``Classical.choice, ``Quot.sound].contains ax do
        throwError "Unapproved axiom in {theorem_name}: {ax}"
    liftIO <| IO.println s!"proofs.rs:checked:{theorem_name}"
"""

outputs = {
    ROOT / "proofs/Proofs/Audit.lean": audit,
    ROOT / "proofs/Proofs/RecorderAudit.lean": recorder,
}
parser = argparse.ArgumentParser()
parser.add_argument("--check", action="store_true")
args = parser.parse_args()
for path, desired in outputs.items():
    if args.check:
        if not path.exists() or path.read_text() != desired:
            print(f"stale generated audit: {path.relative_to(ROOT)}", file=sys.stderr)
            raise SystemExit(1)
    else:
        path.write_text(desired)
print(f"Audits synchronized with {len(names)} checked theorems and {len(mapping)} recorder mapping(s)")
